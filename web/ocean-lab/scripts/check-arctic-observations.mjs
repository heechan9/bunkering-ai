import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import vm from 'node:vm';
import ts from 'typescript';
const root='public/data/arctic-observations/';
const track=JSON.parse(fs.readFileSync(root+'track.json')),ice=JSON.parse(fs.readFileSync(root+'ice.json'));
const exp={};vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/arctic-observations.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,{exports:exp});
let checks=0;const check=(fn)=>{fn();checks++;};
check(()=>assert(exp.validTrack(track)));
check(()=>assert(exp.validIce(ice)));
check(()=>assert.equal(track.rowCount,4314));
check(()=>assert.equal(track.sourceSha256,crypto.createHash('sha256').update(fs.readFileSync(root+'PS155_10min.tsv')).digest('hex')));
check(()=>assert.equal(track.start,'2026-07-04T04:20'));
check(()=>assert.equal(track.end,'2026-08-03T03:04'));
check(()=>assert.equal(track.points.filter(p=>p[3]===null).length,1));
check(()=>assert.equal(ice.date,'2026-01-15'));
check(()=>assert.equal(ice.cells.length,856));
check(()=>assert.equal(ice.cells.filter(p=>p[2]===0).length,526));
check(()=>assert.equal(ice.sampleSpacingKm,200));
check(()=>assert.equal(ice.nativeResolutionKm,25));
check(()=>assert(ice.date<track.start.slice(0,10)));
for(const value of [null,{}, {...track,points:[]},{...track,fuelData:true},{...track,rowCount:3},{...track,points:[track.points[0],track.points[0]]}])check(()=>assert(!exp.validTrack(value)));
for(const value of [null,{}, {...ice,cells:[null]}, {...ice,cells:[]},{...ice,cells:[[0,0,2.51]]},{...ice,cells:[[NaN,0,.5]]},{...ice,status:'unavailable'}])check(()=>assert(!exp.validIce(value)));
check(()=>assert.deepEqual(Array.from(exp.polarPoint(90,0)),[320,320]));
check(()=>assert(Math.abs(exp.polarPoint(70,-45)[0]-320)<1e-8));
check(()=>assert(exp.polarPoint(70,-45)[1]>320));
check(()=>assert(exp.polarPoint(70,45)[0]>320));
check(()=>assert(track.points.every(p=>exp.polarPoint(p[1],p[2]).every(Number.isFinite))));
const ui=fs.readFileSync('components/ocean/ArcticObservations.tsx','utf8');
check(()=>assert(ui.includes('[iceOn,setIceOn]=useState(false)')));
check(()=>assert(ui.includes('NOT the voyage date')&&ui.includes('항해 시기와 다름')));
check(()=>assert(ui.includes('No measured fuel')&&ui.includes('연료 실측')));
check(()=>assert(!ui.includes('reviewArctic')&&!ui.includes('onFormChange')));
console.log(JSON.stringify({checks,passed:checks,trackRows:track.rowCount,iceValidCells:ice.cells.length,iceDate:ice.date,scope:'Source identities, projection orientation, missing data, rejected malformed data, model separation. Browser tested separately.'}));
